  M.poly = (s, n) => { const it = K.pi(s); return K.mkq({ prompt: zs(it.w.replace(it.c, `<u>${it.c}</u>`)), ask: '畫線的字在這裡怎麼唸？', item: it, hint: s.demo }, zy(it.a), it.o.map(zy), n); };
  M.comp = (s, n) => { const it = K.pi(s); return K.mkq({ prompt: zs(it.p.join(' ＋ ') + ' ＝ ❓'), ask: '合起來是哪一個字？', say: '合起來是哪一個字？', item: it, hint: `這個字在「${it.w}」裡出現過。` }, zw(it.c), s.data.filter(x => x !== it).map(x => zw(x.c)), n); };
  M.radical = (s, n) => {
    const g = K.pi(s, s.data), c = P([...g[2]]), others = s.data.filter(x => x !== g).map(x => zw(P([...x[2]]))), tx = `哪一個字跟「${g[1]}」有關？`;
    return K.mkq({ prompt: zw(g[0]), ask: tx, say: tx, item: g, hint: `找找哪個字裡面有「${g[0]}」這個部首。` }, zw(c), others, n);
  };
  M.phonetic = (s, n) => {
    const g = K.pi(s, s.data), c = P([...g[1]]), others = s.data.filter(x => x !== g).map(x => zw(P([...x[1]]))), tx = `哪一個字的讀音和「${g[0]}」最像？`;
    return K.mkq({ prompt: zw(g[0]), ask: tx, item: g, hint: `找找哪個字裡面藏著「${g[0]}」。` }, zw(c), others, n);
  };
  M.fill = (s, n) => { const it = K.pi(s); return K.mkq({ prompt: zs(it.s), ask: '選出正確的字', say: s.g <= 2 ? it.s.replace(/＿+/, it.a) : '', item: it, hint: s.demo }, zw(it.a), it.o.map(zw), n); };
